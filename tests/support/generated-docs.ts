/** The verdict of a cell that came back Ok, as the goldens spell it. */
const OK = 'ok';

/** The refusal of `keel add` in a directory that holds no keel project. */
const NOT_A_PROJECT = 'keel.not-initialised';

/** What `keel add <vertical>` came back as in one scope, and whether the scope comes with it. */
export interface ScopeFacts {
  /** Vertical id → the golden's verdict: {@link OK} or a refusal's code. */
  readonly verdicts: Readonly<Record<string, string>>;
  /** The verticals `keel.dials` shows as coming with the scope (`included`). */
  readonly included: readonly string[];
}

/** One single-service preset, as the documents read it. */
export interface StackFacts extends ScopeFacts {
  /** The preset's id, as `keel new --stack` takes it. */
  readonly id: string;
  /** Its entrypoints, as {@link ENTRYPOINTS} ids, in that list's order. */
  readonly entrypoints: readonly string[];
  /** The verticals its preset installs, in install order. */
  readonly installs: readonly string[];
}

/** One service of a product preset. */
export interface ServiceFacts {
  /** Where the service sits under the product root, as the preset declares it. */
  readonly path: string;
  /** The single-service preset it is scaffolded from. */
  readonly stack: string;
  /** What the product installs in it on top of that preset's own, in install order. */
  readonly extras: readonly string[];
}

/** A product scaffolded under one repository layout. */
export interface LayoutFacts {
  /** The repository layout, as `--layout` takes it. */
  readonly layout: string;
  /** The product root; null where the layout leaves no keel project there. */
  readonly root: ScopeFacts | null;
  /** Service path → that service's scope. */
  readonly services: Readonly<Record<string, ScopeFacts>>;
}

/** One product preset, as the documents read it. */
export interface ProductFacts {
  /** The product preset's id, as `keel new --stack` takes it. */
  readonly id: string;
  /** The verticals its root installs, in install order. */
  readonly installs: readonly string[];
  readonly services: readonly ServiceFacts[];
  /** One per repository layout the composite grid swept it under. */
  readonly layouts: readonly LayoutFacts[];
}

/**
 * What the compatibility matrix and the defaults table are rendered
 * from. {@link DocFacts} extends it for the other regions.
 */
export interface GridFacts {
  /** Every vertical the catalog offers `keel add`, id-sorted. */
  readonly verticals: readonly string[];
  /** The single-service presets, id-sorted. */
  readonly stacks: readonly StackFacts[];
  /** The product presets, id-sorted. */
  readonly products: readonly ProductFacts[];
}

/**
 * Reads {@link GridFacts} from the committed goldens and from
 * `keel.catalog` and `keel.dials` over `mediator`.
 *
 * A single-service preset's verdicts are the brownfield axis's — `keel
 * add` in its fresh scaffold, which the grid holds to the greenfield
 * `--with` verdict (I5) — and a product's are the composite axis's, at
 * its root and in each service, under each layout that axis swept.
 * A cell the golden does not have is a golden older than the catalog,
 * and fails with the order to regenerate the grid first.
 */
export async function gridFacts(
  mediator: Mediator,
  registry: Registry = shippedRegistry,
): Promise<GridFacts> {
  const catalog = expectOk(await mediator.dispatch(catalogQuery()));
  const brownfield = golden('brownfield');
  const composite = golden('composite');
  const verticals = catalog.verticals.map((vertical) => vertical.id);
  const installs = (id: string): readonly string[] => {
    const stack = registry.stacks().find((candidate) => candidate.id === id);
    if (stack === undefined) throw new Error(`the catalog lists '${id}', the registry does not`);
    return stack.verticals.map((vertical) => vertical.id);
  };
  const verdicts = (axis: Golden, scope: string): Record<string, string> =>
    Object.fromEntries(verticals.map((vertical) => [vertical, axis.verdict(scope, vertical)]));
  const dials = async (stack: string, layout?: string): Promise<DialOptions> =>
    expectOk(
      await mediator.dispatch(
        dialsQuery({
          target: {
            kind: 'new-project',
            stack,
            ...(layout === undefined ? {} : { layout: layout as RepoLayout }),
          },
        }),
      ),
    );

  const stacks: StackFacts[] = [];
  const products: ProductFacts[] = [];
  for (const stack of [...catalog.stacks].sort((a, b) => a.id.localeCompare(b.id))) {
    if (stack.services.length === 0) {
      stacks.push({
        id: stack.id,
        entrypoints: ENTRYPOINTS.filter((entry) => stack.tags.includes(entry.tag)).map(
          (entry) => entry.id,
        ),
        installs: installs(stack.id),
        verdicts: verdicts(brownfield, stack.id),
        included: includedIn((await dials(stack.id)).verticals),
      });
      continue;
    }
    const preset = registry.stacks().find((candidate) => candidate.id === stack.id);
    const services: ServiceFacts[] = stack.services.map((service) => ({
      path: service.path,
      stack: service.stack,
      extras: (
        preset?.services?.find((declared) => declared.path === service.path)?.extraVerticals ?? []
      ).map((vertical) => vertical.id),
    }));
    const layouts: LayoutFacts[] = [];
    for (const layout of composite.layoutsOf(stack.id)) {
      const options = await dials(stack.id, layout);
      const root = verdicts(composite, `${stack.id}/${layout}`);
      layouts.push({
        layout,
        // What the root comes with is what `keel.dials` reads as coming
        // with the product: its own verticals, and what the services
        // that could have it have — where `keel add` at the root is an
        // Ok that adds nothing (the composite grid holds the two equal).
        root: Object.values(root).every((verdict) => verdict === NOT_A_PROJECT)
          ? null
          : { verdicts: root, included: includedIn(options.verticals) },
        services: Object.fromEntries(
          services.map((service) => [
            service.path,
            {
              verdicts: verdicts(composite, `${stack.id}/${layout}/${service.path}`),
              included: includedIn(
                options.services.find((dialled) => dialled.path === service.path)?.verticals ?? [],
              ),
            },
          ]),
        ),
      });
    }
    products.push({ id: stack.id, installs: installs(stack.id), services, layouts });
  }
  return { verticals, stacks, products };
}

function includedIn(options: readonly VerticalOption[]): readonly string[] {
  return options.filter((option) => option.readiness === 'included').map((option) => option.id);
}

/** Where the finder places presets: one language and framework, and what each set of ways in names. */
